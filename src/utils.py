def handle_images_to_video_command(args):
    input_file_or_directory = args["input_file_or_directory"]
    video_frame_rate = args["video_frame_rate"]
    output_file_or_directory_name = args["output_file_or_directory_name"]
    ffmpeg_full_path = args["ffmpeg_executable_path"]
    file_extension = args["file_extension"]
    video_name = args["video_name"]

    video_name_full = os.path.join(output_file_or_directory_name[0], video_name)

    # Get a list of all files that match the pattern
    files = glob.glob(os.path.join(input_file_or_directory, "*" + file_extension))

    # Sort the files to ensure we get the first one
    files.sort()

    if files:
        with Image.open(files[0]) as img:
            width, height = img.size
    else:
        logger.critical("No images found in the input directory")
            
  
    input_files_pattern = f"{input_file_or_directory}//%12d{file_extension}"
    input_files_pattern = os.path.normpath(input_files_pattern)

    command = [
        "ffmpeg",
        "-loglevel",
        "warning",
        "-hide_banner",
        "-framerate",
        f"{video_frame_rate}",
        "-i",
        input_files_pattern,
        "-r",
        f"{video_frame_rate}",
        "-filter_complex",
        f"scale={width}:{height}:force_original_aspect_ratio=decrease,pad={width}:{height}:(ow-iw)/2:(oh-ih)/2",
        "-c:v",
        "libx264",
        f"{video_name_full}.mp4",
    ]

    run_ffmpeg_command(
        command=command, ffmpeg_executable_path=ffmpeg_full_path
    )

    return True


