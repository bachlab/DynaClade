def handle_split_videos_command(args):
    """
    videos_full_path    : full path of directory containing the videos
    ffmpeg_full_path    : full path of directory containing the ffmpeg.exe file
    number_videos_split : total number of videos to split frome video file
    rows      : total number of videos per row on the original video file
    columns   : total number of videos per column on the original video file
    video_extension     : video extension type
    bit_rate            : bit rate original video in bits/second
    """
    videos_full_path = args["input_file_or_directory"]
    ffmpeg_full_path = args["ffmpeg_executable_path"]
    number_videos_split = args["number_videos_split"]
    rows = args["rows"]
    columns = args["columns"]
    video_extension = args["video_extension"]
    bit_rate = args["bit_rate"]
    output_path = args["output_file_or_directory_name"][0]
    crop_range = args["crop_range"]

    if output_path is None:
        output_path = videos_full_path

    items = [videos_full_path]

    crop_section = []
    for r in range(1, rows + 1):
        for c in range(1, columns + 1):
            if r == 1:
                h_id = 0
            else:
                h_id = f"in_h*{r-1}/{rows}"
            if c == 1:
                w_id = 0
            else:
                w_id = f"in_w*{c-1}/{columns}"

            new_crop_index = f"crop=in_w/{columns}:in_h/{rows}:{w_id}:{h_id}"
            crop_section.append(new_crop_index)

    for fd in items:
        file_name_to_split = fd
        fd_base = os.path.basename(fd)
        out_dir = f'{fd_base[:fd_base.index(f".{video_extension}")]}'
        out_parent = os.path.join(output_path, out_dir)
        if not os.path.exists(out_parent):
            os.makedirs(out_parent)

        for i in tqdm(
            list(range(number_videos_split)),
            desc=f"Spliting video",
            leave=False,
        ):
            try:
                fd_base = os.path.basename(fd)
                file_name = fd_base[
                    : fd_base.index(f".{video_extension}")
                ] + (f"_cam_{i}.mp4")
                output_file_name = os.path.join(out_parent, file_name)
                output_file_name_parent = os.path.dirname(output_file_name)
                if not os.path.exists(output_file_name_parent):
                    os.makedirs(output_file_name_parent)

                crop_range = crop_section[i]
                command = [
                    "ffmpeg",
                    "-loglevel",
                    "warning",
                    "-hide_banner",
                    "-i",
                    file_name_to_split,
                    "-b:v",
                    f"{bit_rate}M",
                    "-filter:v",
                    crop_range,
                    "-c:a",
                    "copy",
                    output_file_name,
                ]

                run_ffmpeg_command(
                    command=command, ffmpeg_executable_path=ffmpeg_full_path
                )

            except Exception as e:
                print(f"Failed to process video {fd}. Reason: {e}")


