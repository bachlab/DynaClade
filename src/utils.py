def smoothing_sg(data: list, window: int = 61, order: int = 2, axis: int = 0):
    if (window % 2) == 0:
        window = window + 1

    smoothened = scipy.signal.savgol_filter(
        x=data, window_length=window, polyorder=order, axis=axis
    )

    return smoothened


def euclidean_distance(
    vector1: pd.DataFrame, vector2: pd.DataFrame
) -> np.ndarray:
    """
    Computes euclidean distance between 2 points defined \n
    in cartesian space (x,y,z)

    Vector1 and Vector2: pd.DataFrame [n x 3]
        where rows represent points, and columns \n
        the x,y,z positons of the "n" point

    Descpription
    ---
    Calculated from the Cartesian coordinates of \n
    the points using the Pythagorean theorem
    """

    distance_xyz = vector1.sub(vector2.values, axis="columns").values
    distance = np.sqrt(
        distance_xyz[:, 0] ** 2
        + distance_xyz[:, 1] ** 2
        + distance_xyz[:, 2] ** 2
    )

    return distance


# @tictoc
def distance_features(
    data: Union[str, pd.DataFrame],
    stickfigure: 'StickFigure',
    save: bool = False,
    output: str = None,
    normalise: bool = True,
) -> pd.DataFrame:
    if save:
        if not os.path.exists(output):
            message = (
                f"|distance_features| Output file was "
                + f"not found. Path: [{output}]"
            )
            logger.critical(message)
            return

    if type(data) == str:
        if os.path.isfile(data):
            df = pd.read_csv(data, index_col=0)
        else:
            message = (
                f"|distance_features| Data file could not be found. "
                + f"File provided: [{data}]"
            )
            logging.critical(message)

    elif type(data) == pd.DataFrame:
        df = data

    else:
        message = (
            f"|distance_features| Data input must be a file or "
            + f"pandas DataFrame. Data input type: {type(data)}"
        )
        logging.critical(message)

    processed = []
    distances = pd.DataFrame()

    for key in stickfigure._markers:
        current_not_key = [c for c in stickfigure._markers if key not in c]

        for i in current_not_key:
            current_pair = f"{key}_{i}"
            rigid_segment = any(
                [
                    (key in segment) and (i in segment)
                    for segment in stickfigure.body.values()
                ]
            )
            target_markers = (key in stickfigure._markers) and (
                i in stickfigure._markers
            )

            if not rigid_segment and target_markers:
                already_processed = any(
                    [((i in p) and (key in p)) for p in processed]
                )

                if already_processed == False:
                    distances[current_pair] = euclidean_distance(
                        vector1=df[stickfigure._markers_xyz[key]],
                        vector2=df[stickfigure._markers_xyz[i]],
                    )
                    processed.append(current_pair)

    if normalise:
        RShin_norm = np.median(
            euclidean_distance(
                vector1=df[stickfigure._segments_xyz["RShin"][0]],
                vector2=df[stickfigure._segments_xyz["RShin"][1]],
            )
        )
        RThigh_norm = np.median(
            euclidean_distance(
                vector1=df[stickfigure._segments_xyz["RThigh"][0]],
                vector2=df[stickfigure._segments_xyz["RThigh"][1]],
            )
        )
        Back_norm = np.median(
            euclidean_distance(
                vector1=df[stickfigure._segments_xyz["Back"][0]],
                vector2=df[stickfigure._segments_xyz["Back"][1]],
            )
        )
        norm_base = RShin_norm + RThigh_norm + Back_norm
        distances = distances / norm_base

    if save:
        output_name = f"distance_features.csv"
        distances.to_csv(
            os.path.join(output, output_name), header=True, index=False
        )

    return distances, norm_base


def diff_dataframe(
    data: pd.DataFrame,
    delta: Union[int, float],
    columns: list,
    data_sample_rate: int,
    suffix: str = "_delta_",
    axis: int = 0,
    smoothing_data: bool = True,
) -> pd.DataFrame:
    """
    Compute the difference between consecutive angles
    """
    try:
        zeros = pd.DataFrame([[0] * len(columns)], columns=columns)
        data_diff = pd.DataFrame(
            diff(data, axis=axis) / delta, columns=columns
        )
        differentiated_data = pd.concat(
            [zeros, data_diff], ignore_index=True
        ).add_suffix(suffix)
        if smoothing_data:
            differentiated_data = smoothing(
                data=differentiated_data, data_sample_rate=data_sample_rate
            )

        return differentiated_data

    except Exception as e:
        logging.critical(
            f"|distance_features| An error occurred"
            + f"while differentiating the data: {e}"
        )
        return pd.DataFrame()

def angle(x: np.ndarray, y: np.ndarray) -> float:
    """compute angle between 2 vectors"""
    angle: float = 180 - np.degrees(
        np.arctan2(np.linalg.norm(np.cross(x, y)), np.dot(x, y))
    )

    return angle

