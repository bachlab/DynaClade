def file_extension_check(file_extension: str) -> str:
    """sanity check for file extension"""
    if file_extension[0] == ".":
        file_extension = f"{file_extension}"
    else:
        file_extension = f".{file_extension}"

    return file_extension


def ffmpeg_process(
    command: str,
    input_file_or_directory: Union[str, List[str]],
    ffmpeg_executable_path: str,
    output_file_or_directory_name: str,
    bit_rate: int = None,
    crop_range: str = None,
    file_extension: str = None,
    trim_start: int = None,
    trim_end: int = None,
    data_sample_rate: int = None,
    search_pattern: str = None,
    video_name: str = None,
    video_frame_rate: int = None,
    overwrite_path: bool = True,
    number_videos_split: int = 10,
    rows: int = 3,
    columns: int = 4,
    video_extension: str = "mkv",
    extract_calibration: bool = False,
) -> bool:
    original_directory = os.getcwd()
    paths: FilesList = list_directory_items(
        input_file_or_directory, recursive=True, search_pattern=search_pattern
    )
    unique_parents = paths["unique_parents"]

    if len(paths["items"]) == 0:
        logger.critical(
            f'|ffmpeg_process| The input file or directory "{input_file_or_directory}" could not be found or is empty'
        )
        return

    if file_extension:
        file_extension = file_extension_check(file_extension)

    mode_ = paths["mode"]
    if mode_ == "file":
        file_name = paths["items"]
        parent_folder = unique_parents
    elif mode_ == "path":
        parent_folder = unique_parents
    else:
        logger.critical(
            f"|ffmpeg_process| input file or directory {input_file_or_directory} was not identified with any file or directory"
        )

    if not output_file_or_directory_name:
        if len(parent_folder) > 1:
            output_file_or_directory_name = [
                create_directory(
                    os.path.join(os.path.dirname(i), "ffmpeg_output")
                )
                for i in parent_folder
            ]
        else:
            output_file_or_directory_name = [
                create_directory(
                    os.path.join(
                        os.path.dirname(parent_folder[0]), "ffmpeg_output"
                    )
                )
            ]
    else:
        output_file_or_directory_name = [output_file_or_directory_name]

    args = locals()

    if command == "images_to_video":
        handle_images_to_video_command(args)
    elif command == "trim":
        handle_trim_command(args)
    elif command == "split_videos":
        handle_split_videos_command(args)
    elif command == "extract_images":
        handle_extract_images_command(args)
    else:
        logger.critical("|ffmpeg_process| No ffmpeg command was not found")
    
    return True


