def logging_system(
    debug_level_console: str = "error",
    debug_level_log_file: str = "error",
    clean_logs_file: bool = True,
) -> None:
    """logging system"""
    global logger

    debug_level_values: dict = {
        "debug": logging.DEBUG,  # 10
        "info": logging.INFO,  # 20
        "warning": logging.WARNING,  # 30
        "error": logging.ERROR,  # 40
        "critical": logging.CRITICAL,  # 50
    }

    logger = logging.getLogger()
    logger.setLevel(logging.DEBUG)

    # remove any previously added handles if exist
    while len(logger.handlers) != 0:
        logger.handlers.pop()

    formatter = logging.Formatter(
        bold_color.BOLD
        + bold_color.YELLOW
        + "[%(asctime)s] %(levelname)s : %(message)s [%(filename)s Line:%(lineno)d]"
        + bold_color.END,
        datefmt="%d-%m-%Y %I:%M:%S",
    )

    logFormatterFile = logging.Formatter(
        "[%(asctime)s] %(levelname)s: %(message)s [%(filename)s Line:%(lineno)d]",
        datefmt="%d-%m-%Y %I:%M:%S",
    )

    logs_path = os.path.join(os.path.dirname(__file__), "logs.log")
    if clean_logs_file and os.path.isfile(logs_path):
        open(logs_path, "w").close()

    # create log handlers
    consoleHandler = logging.StreamHandler()
    fileHandler = logging.FileHandler(logs_path, "w", "utf-8")
    # set levels
    consoleHandler.setLevel(
        debug_level_values.get(debug_level_console.lower())
    )
    fileHandler.setLevel(debug_level_values.get(debug_level_log_file.lower()))
    # set format
    consoleHandler.setFormatter(formatter)
    fileHandler.setFormatter(logFormatterFile)
    # add handlers to logger
    logger.addHandler(consoleHandler)
    logger.addHandler(fileHandler)

    return None


