import pandas as pd
import numpy as np
from scipy.signal import firwin, filtfilt
import matplotlib.pyplot as plt

def downsample_signal(df: pd.DataFrame, original_fs: int, target_fs: int = 100, pad_factor: int = 20) -> pd.DataFrame:
    """
    Downsample DataFrame columns except 'time' using decimation with anti-aliasing.

    Args:
        df: Input DataFrame with 'time' and motion data columns
        original_fs: Original sampling frequency in Hz
        target_fs: Target sampling frequency in Hz, default 100Hz

    Returns:
        pd.DataFrame: Downsampled DataFrame with original time column
    """
    # Check if 'time' column exists
    if 'time' not in df.columns:
        raise KeyError("The DataFrame does not contain a 'time' column.")

    # If target_fs >= original_fs, no downsampling needed
    if target_fs >= original_fs:
        logger.info(f"Target frequency ({target_fs}Hz) >= original frequency ({original_fs}Hz). No downsampling needed.")
        return df

    # Separate time column
    time_col = df['time'].copy()
    data_cols = df.drop('time', axis=1)

    # Calculate downsampling factor
    downsampling_factor = int(original_fs / target_fs)
    
    # Ensure downsampling factor is at least 1
    if downsampling_factor < 1:
        logger.warning(f"Downsampling factor would be {downsampling_factor}, setting to 1")
        downsampling_factor = 1

    # Downsample each column except time
    downsampled_data = {}
    for col in data_cols.columns:
        try:
            # Pad the signal at the extremes
            pad_len = downsampling_factor * pad_factor
            padded_signal = np.pad(data_cols[col].values, (pad_len, pad_len), mode='edge')

            # Design a zero-phase FIR filter
            nyquist_freq = original_fs / 2
            cutoff_freq = target_fs / 2  # Nyquist frequency of the target sampling rate
            
            # Ensure cutoff frequency is valid (greater than 0 and less than nyquist)
            if cutoff_freq <= 0 or cutoff_freq >= nyquist_freq:
                logger.warning(f"Invalid cutoff frequency {cutoff_freq}Hz for column {col}. Using {nyquist_freq * 0.8}Hz instead.")
                cutoff_freq = nyquist_freq * 0.8
            
            numtaps = 101  # Number of filter coefficients (taps)
            filter_coefs = firwin(numtaps, cutoff_freq / nyquist_freq)

            # Apply the filter in zero-phase mode using filtfilt
            filtered_signal = filtfilt(filter_coefs, 1.0, padded_signal)

            # Decimate the filtered signal
            downsampled_signal = filtered_signal[pad_len:-pad_len:downsampling_factor]

            downsampled_data[col] = downsampled_signal

        except Exception as e:
            logger.warning(f"Error downsampling column {col}: {str(e)}")
            # If downsampling fails, use simple decimation
            try:
                downsampled_data[col] = data_cols[col].values[::downsampling_factor]
            except Exception as e2:
                logger.error(f"Failed to downsample column {col} even with simple decimation: {str(e2)}")
                # Keep original data if all else fails
                downsampled_data[col] = data_cols[col].values

    # Create new DataFrame with downsampled data
    try:
        downsampled_df = pd.DataFrame(downsampled_data)
    except Exception as e:
        logger.error(f"Error creating downsampled DataFrame: {str(e)}")
        # Return original DataFrame if creation fails
        return df

    # Add back time column with correct downsampled indices
    try:
        # Ensure time_col is a NumPy array for proper slicing
        time_col_np = np.array(time_col)
        
        # Calculate the expected length of downsampled time
        expected_length = len(time_col_np) // downsampling_factor
        
        # Ensure we don't exceed the length of downsampled data
        actual_length = min(expected_length, len(downsampled_df))
        
        downsampled_time_col = time_col_np[::downsampling_factor][:actual_length]
        
        # Ensure the time column length matches the data length
        if len(downsampled_time_col) != len(downsampled_df):
            # Truncate the DataFrame to match time column length
            downsampled_df = downsampled_df.iloc[:len(downsampled_time_col)]
        
        downsampled_df.insert(0, 'time', downsampled_time_col)
        
    except Exception as e:
        logger.error(f"Error adding time column to downsampled DataFrame: {str(e)}")
        # If time column addition fails, return original DataFrame
        return df

    # Plot the original and downsampled signals for visual inspection
    plot_figure = False
    if plot_figure:
        plt.figure(figsize=(10, 6))
        c=0
        if c==0:
            for col in data_cols.columns:
                plt.plot(df['time'], df[col], label=f'Original {col} ({original_fs}Hz)')
                plt.plot(downsampled_df['time'], downsampled_df[col], label=f'Downsampled {col} ({target_fs}Hz)')
                c+=1
        plt.xlabel('Time (seconds)')
        plt.ylabel('Amplitude')
        plt.title('Original vs. Downsampled Signal')
        plt.legend()
        plt.grid(True)
        plt.show()

    return downsampled_df


