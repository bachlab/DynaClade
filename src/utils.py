@dataclass
class StickFigure:
    """create a stick figure representation for motion analysis and animation

    Attributes
    ----------

    Public:
    ------
        name :  str
            Object name
        body : dict
            Contains segment names as keys and a tuple with start and end segment marker names
        data_mapping : bool
            If True, remaps marker names provided as a dictionary where keys are current marker names, and values are the new marker names

    Private:
    -------
        _markers_xyz : int
            Marker coordinates in cartesian space (x, y, z)
        _segments_xyz : int
            Segment coordinates in cartesian space (x, y, z)
        _markers : list[str]
            Marker names
        _segments : list[str]
            Segment names
        _segment_lengths : dict[(str,str)]
            Segment lengths set to 'None' by default
        _num_markers : int
            Number of markers
        _num_segments : int
            Number of segments
        _id : str
            Internal autogenerated 12-uppercase id string
        _linked_to : dict
            List of segments and markers linked and connected with each other
    """

    name: Optional[str] = field(default=None)
    body: Dict[str, tuple[str, str]] = field(default_factory=dict, repr=False)
    data_mapping: Optional[Union[Dict[str, str], None]] = field(
        default=None, repr=False
    )

    _markers_xyz: dict = field(init=False, default_factory=dict, repr=False)
    _segments_xyz: dict = field(init=False, default_factory=dict, repr=False)
    _markers: list[str] = field(init=False, default_factory=list)
    _segments: list[str] = field(init=False, default_factory=list)
    _segment_lengths: dict[(str, str)] = field(
        init=False, default_factory=dict, repr=False
    )
    _num_markers: int = field(init=False, repr=False)
    _num_segments: int = field(init=False, repr=False)
    _id: str = field(init=False, default_factory=generate_id, repr=False)
    _linked_to: dict = field(init=False, default_factory=dict, repr=False)

    def __post_init__(self) -> None:
        self._markers = sorted(
            set([y for x in self.body.values() for y in x])
        )
        self._segments = sorted(set([x for x in self.body.keys()]))
        self._num_markers = len(self._markers)
        self._num_segments = len(self._segments)
        self._linked_to = dict.fromkeys(self._segments, dict())

        for s1 in self._segments:
            tempList = list()
            for s2 in self._segments:
                if s1 != s2:
                    marker1 = self.body.get(s2)[0]
                    marker2 = self.body.get(s2)[1]
                    markersout = self.body.get(s1)
                    if marker1 in markersout:
                        tempList.append((s2, marker1))
                    elif marker2 in markersout:
                        tempList.append((s2, marker2))
                self._linked_to[s1] = dict(tempList)

        self._segment_lengths = dict.fromkeys(self._segments)
        self._markers_xyz = dict.fromkeys(self._markers)

        if self.data_mapping is not None:
            if (
                self.data_mapping.keys()
                == dict.fromkeys(self._markers).keys()
            ):
                for k, v in self.data_mapping.items():
                    temp = [f"{v}_{c}" for c in ["x", "y", "z"]]
                    self._markers_xyz.update([(k, temp)])
            else:
                message = (
                    f"StickFigure dataclase could not be created as "
                    + f'"data_mapping" argument does not contain all values'
                    + f"for marker remapping"
                )
                logger.critical(message)
                exit()
        else:
            self.data_mapping: dict = {}
            for k in self._markers:
                temp = [f"{k}_{c}" for c in ["x", "y", "z"]]
                self._markers_xyz.update([(k, temp)])
                self.data_mapping.update([(k, k)])

        self._segments_xyz = dict.fromkeys(self._segments)
        for s in self._segments:
            temp = [self._markers_xyz.get(k) for k in self.body.get(s)]
            self._segments_xyz.update([(s, temp)])


